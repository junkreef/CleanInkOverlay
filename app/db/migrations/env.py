"""Alembic environment: the target metadata is the ORM (app.db.models). The DB file comes from, in order,
`-x db=PATH` on the command line, the `sqlalchemy.url` the app sets programmatically (app.db.migrate), or alembic.ini."""
import os, sys
from logging.config import fileConfig
from alembic import context
from sqlalchemy import engine_from_config, event, pool

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
if ROOT not in sys.path: sys.path.insert(0, ROOT)
from app.db.engine import db_url
from app.db.models import Base

config = context.config
if config.config_file_name is not None and 'loggers' in config.file_config.sections():
    fileConfig(config.config_file_name)
if config.get_main_option('db_path'):                    # set by app.db.migrate
    config.set_main_option('sqlalchemy.url', db_url(config.get_main_option('db_path')).render_as_string(hide_password=False))
elif context.get_x_argument(as_dictionary=True).get('db'):
    config.set_main_option('sqlalchemy.url', db_url(context.get_x_argument(as_dictionary=True)['db']).render_as_string(hide_password=False))

target_metadata = Base.metadata


def run_migrations_offline():
    context.configure(url=config.get_main_option('sqlalchemy.url'), target_metadata=target_metadata,
                      literal_binds=True, dialect_opts={'paramstyle': 'named'}, render_as_batch=True)
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online():
    engine = engine_from_config(config.get_section(config.config_ini_section, {}), prefix='sqlalchemy.', poolclass=pool.NullPool)

    @event.listens_for(engine, 'connect')
    def _connect(dbapi_con, _rec):
        dbapi_con.isolation_level = None                    # pysqlite: we issue BEGIN ourselves so DDL is inside the transaction
        dbapi_con.execute('PRAGMA foreign_keys = OFF')      # tables are rebuilt by copy + drop + rename (must be outside a transaction)

    @event.listens_for(engine, 'begin')
    def _begin(conn):
        conn.exec_driver_sql('BEGIN')

    with engine.connect() as connection:
        # transactional_ddl: a migration that fails half-way rolls back instead of leaving *_new tables behind.
        # render_as_batch: SQLite cannot ALTER most things, so autogenerated migrations use "move and copy" batch ops
        context.configure(connection=connection, target_metadata=target_metadata, render_as_batch=True, transactional_ddl=True)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
